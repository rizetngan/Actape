import Foundation
import CoreGraphics
import CoreFoundation

/// Detects physical extra mouse buttons directly. No shortcut remapper is needed.
/// The tap is active while Macrobot is running, including when its window is not focused.
@MainActor
final class MouseTriggerMonitor {
    private var eventTap: CFMachPort?
    private var runLoopSource: CFRunLoopSource?
    private var consumedDowns: Set<Int> = []

    var resolveMacro: ((Int) -> UUID?)?
    var onCapture: ((UUID, Int) -> Void)?
    var onTrigger: ((UUID) -> Void)?

    var isSuspended = false
    private(set) var captureMacroID: UUID?
    var isRunning: Bool { eventTap != nil }

    func start() -> Bool {
        guard !isRunning else { return true }
        let mask: CGEventMask =
            (1 << CGEventType.otherMouseDown.rawValue) |
            (1 << CGEventType.otherMouseUp.rawValue)

        let refcon = Unmanaged.passUnretained(self).toOpaque()
        guard let tap = CGEvent.tapCreate(
            tap: .cgSessionEventTap,
            place: .headInsertEventTap,
            options: .defaultTap,
            eventsOfInterest: mask,
            callback: { _, type, event, info in
                guard let info else { return Unmanaged.passUnretained(event) }
                let monitor = Unmanaged<MouseTriggerMonitor>.fromOpaque(info).takeUnretainedValue()
                let swallow = MainActor.assumeIsolated {
                    monitor.handle(type: type, event: event)
                }
                return swallow ? nil : Unmanaged.passUnretained(event)
            },
            userInfo: refcon
        ) else { return false }

        let source = CFMachPortCreateRunLoopSource(kCFAllocatorDefault, tap, 0)
        CFRunLoopAddSource(CFRunLoopGetMain(), source, .commonModes)
        CGEvent.tapEnable(tap: tap, enable: true)
        eventTap = tap
        runLoopSource = source
        return true
    }

    func captureNextButton(for macroID: UUID) {
        captureMacroID = macroID
    }

    func cancelCapture() {
        captureMacroID = nil
    }

    func stop() {
        cancelCapture()
        if let eventTap { CGEvent.tapEnable(tap: eventTap, enable: false) }
        if let runLoopSource {
            CFRunLoopRemoveSource(CFRunLoopGetMain(), runLoopSource, .commonModes)
        }
        eventTap = nil
        runLoopSource = nil
        consumedDowns.removeAll()
    }

    private func handle(type: CGEventType, event: CGEvent) -> Bool {
        if type == .tapDisabledByTimeout || type == .tapDisabledByUserInput {
            if let eventTap { CGEvent.tapEnable(tap: eventTap, enable: true) }
            return false
        }
        guard type == .otherMouseDown || type == .otherMouseUp else { return false }
        // Never re-trigger a macro from an event generated by our own player.
        if event.getIntegerValueField(.eventSourceUnixProcessID) == Int64(ProcessInfo.processInfo.processIdentifier) {
            return false
        }
        let button = Int(event.getIntegerValueField(.mouseEventButtonNumber))
        guard button >= 2 else { return false }

        // Recording should capture raw mouse actions; do not launch a macro from them.
        if isSuspended { return false }

        if type == .otherMouseUp {
            return consumedDowns.remove(button) != nil
        }

        if let macroID = captureMacroID {
            captureMacroID = nil
            consumedDowns.insert(button)
            onCapture?(macroID, button)
            return true
        }

        guard let macroID = resolveMacro?(button) else { return false }
        // Only the initial physical down triggers playback, not auto-repeated downs.
        if consumedDowns.insert(button).inserted {
            onTrigger?(macroID)
        }
        // Swallow native Back/Forward behavior for assigned buttons.
        return true
    }
}
